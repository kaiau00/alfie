import CryptoKit
import Foundation
import Testing
@testable import MoeLicence

/// The format is implemented twice — in `LicenceKey.swift`, which reads keys,
/// and in `scripts/make-licence.py`, which writes them. Nothing forces the two
/// to agree except this file.
///
/// The danger it is here for is specific and expensive: the two halves drift,
/// keys go out to customers that the app cannot read, and nobody finds out
/// until somebody has already paid. A golden vector is the cheapest possible
/// insurance against that, because it fails at `swift test` rather than in an
/// inbox.
///
/// The seed below is 0, 1, 2 … 31. It is a test fixture and nothing else. The
/// real signing key is not in this repo, is not generated by any test, and
/// lives where docs/RELEASING.md §1.5 says it lives.
struct MintingToolTests {

    private let seed = Data(0..<32)

    /// Byte for byte what `scripts/make-licence.py` printed for this licence.
    /// Regenerate with `python3 scripts/make-licence.py --self-test` and the
    /// same inputs if the format ever changes on purpose — and if it changes
    /// by accident, this is the line that says so.
    private let golden = """
    MOE01-040GG-0820C-20A1G-71010-20831-XGP8R-A0CNW-62VBG-DHJJW-RVFDM-20429-\
    40M10-N4860-41FC9-672BF-3Z5VE-RQ0WX-8MJKZ-9WVW6-T0S11-CCSQQ-8B0VD-6MK2W-\
    20TYZ-GWBSX-B778P-PCXB0-GS3DQ-E090C-Y7S2B-YSMBX-R89Q1-RX7YN-FKV02-RMW
    """

    @Test func swiftReadsWhatThePythonToolWrites() throws {
        let key = try Curve25519.Signing.PrivateKey(rawRepresentation: seed)
        let licence = try LicenceKey.read(golden, publicKey: key.publicKey.rawRepresentation).get()

        #expect(licence.id == "0102030405060708")
        #expect(licence.tier == .pro)
        #expect(licence.buyer == "ada@example.com")
        #expect(licence.macs == 2)

        var utc = Calendar(identifier: .gregorian)
        utc.timeZone = TimeZone(identifier: "UTC")!
        #expect(utc.dateComponents([.year, .month, .day], from: licence.issued)
                == DateComponents(year: 2026, month: 5, day: 29))
        #expect(licence.updateWindowEnds.map { utc.dateComponents([.year, .month, .day], from: $0) }
                == DateComponents(year: 2027, month: 5, day: 29))
    }

    @Test func theTwoImplementationsLayThePayloadOutIdentically() throws {
        // Everything before the signature — field order, tag numbers, the
        // 2020-01-01 day epoch, the alphabet, the grouping — has to agree
        // byte for byte, and this is what says so.
        //
        // The signature itself is deliberately *not* compared. CryptoKit's
        // Ed25519 is randomised: signing the same bytes with the same key
        // twice gives two different signatures, both valid. RFC 8032's
        // reference signer, which the Python tool uses, is deterministic.
        // Comparing whole keys would fail for that reason and no other, which
        // is why the test above verifies the Python key rather than matching
        // it character by character.
        let key = try Curve25519.Signing.PrivateKey(rawRepresentation: seed)
        var utc = Calendar(identifier: .gregorian)
        utc.timeZone = TimeZone(identifier: "UTC")!

        let mine = LicenceKey.mint(
            Licence(id: "0102030405060708", tier: .pro, buyer: "ada@example.com",
                    issued: utc.date(from: DateComponents(year: 2026, month: 5, day: 29))!,
                    updateWindowEnds: utc.date(from: DateComponents(year: 2027, month: 5, day: 29))!,
                    macs: 2),
            signedBy: key)

        #expect(payload(of: mine) == payload(of: golden))
        #expect(payload(of: golden).count == 42)
    }

    /// Everything up to the signature: the 42 bytes both tools have to agree
    /// on. The last 66 are the signature and the checksum.
    private func payload(of key: String) -> Data {
        let blob = Base32.decode(key.dropFirst(6).replacingOccurrences(of: "-", with: "")) ?? Data()
        return blob.prefix(max(0, blob.count - 66))
    }

    @Test func aKeyStaysShortEnoughToPasteAndReadAloud() {
        // 213 characters, six lines in an email at 40 to a line. Sublime Text
        // and JetBrains both ship longer ones; this is inside what people
        // already accept, and every character of it is unambiguous.
        #expect(golden.count == 213)
    }
}
