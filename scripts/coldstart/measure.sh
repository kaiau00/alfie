#!/bin/bash
# Cold start per turn (docs/ONE-AGENT.md §10 "Falsified if", §11 item 5,
# CLOUD-SHARED.md §3.4).
#
# Spawns the turn launcher once per turn with a per-tenant HOME and a *stubbed*
# model, so what is timed is the runtime and not an LLM. Three stamps per turn:
#
#   t0  the worker decided to answer          (SPAWN)
#   t1  Hermes asked the model something      (POST /v1/chat/completions)
#   t2  the reply is on the worker's stdout   (DONE)
#
# t1 - t0 is the cold start: everything the runtime does before a model could
# emit a first token.
#
# **The environment comes from the product and is not written here.**
# `.build/coldstart/product-env` is generated by
# `TenantIsolationTests.exportTheChildEnvironment` from `TenantHome.environment()`
# itself. That is the whole point: the first measurement was wrong because the
# harness set `NO_PROXY` and the product did not, and the *second* version of
# this script fixed the number by hand-copying the list — re-creating the same
# two-files-agreeing failure, and carrying two variables
# (`HERMES_SKIP_NODE_BOOTSTRAP`, `HERMES_YOLO_MODE`) that exist nowhere in the
# product at all. Run ./scripts/test.sh first; this refuses to guess.
#
# The only things added on top are what a *deployment* supplies and a tenant
# does not: the model endpoint, its key, and HERMES_CHECKOUT.
#
# MOE_COLDSTART_NO_PROXY=0 drops the proxy pair, which is how §16.1's
# counterfactual is a measurement rather than a claim.
#
# Nothing here touches ~/.hermes: HOME and HERMES_HOME are under .build,
# PYTHONDONTWRITEBYTECODE stops __pycache__ landing in the checkout, no gateway
# is started, and the stub listens on 45677 — never 8642.
#
#   PROFILE=minimal   no toolsets  (the floor)
#   PROFILE=cloud     the toolsets CLOUD-AUDIT.md says survive off the Mac
set -u
ROOT="${MOE_COLDSTART_WORK:-$(cd "$(dirname "$0")/../.." && pwd)/.build/coldstart}"
SELF="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$SELF/../.." && pwd)"
mkdir -p "$ROOT"
HERMES="${HERMES_CHECKOUT:-$HOME/.hermes/hermes-agent}"
PY="$HERMES/.venv/bin/python"
PORT=${PORT:-45677}
RUNS=${RUNS:-10}
PROFILE=${PROFILE:-minimal}

ENV_FILE="$REPO/.build/coldstart/product-env"
if [[ ! -f "$ENV_FILE" ]]; then
    echo "error: $ENV_FILE is missing." >&2
    echo "It is generated from TenantHome.environment() by the test suite, so that" >&2
    echo "this script cannot describe an environment the product does not produce." >&2
    echo "Run ./scripts/test.sh, then this again." >&2
    exit 1
fi

export PYTHONDONTWRITEBYTECODE=1
export STUB_STAMPS="$ROOT/stamps-$PROFILE.txt"
: > "$STUB_STAMPS"

"$PY" "$SELF/stub_model.py" "$PORT" > "$ROOT/stub.log" 2>&1 &
STUB=$!
trap 'kill $STUB 2>/dev/null' EXIT
sleep 1
if ! kill -0 $STUB 2>/dev/null; then echo "stub did not start:"; cat "$ROOT/stub.log"; exit 1; fi

write_config() {
  local home="$1"
  cat > "$home/config.yaml" <<YAML
model:
  provider: custom
  model: stub-model
  base_url: http://127.0.0.1:$PORT/v1
YAML
  if [[ "$PROFILE" == "cloud" ]]; then
    cat >> "$home/config.yaml" <<'YAML'
tools:
  tool_search:
    enabled: true
platform_toolsets:
  cli:
  - web
  - vision
  - file
  - delegation
  - cronjob
  - skills
  - memory
  - session_search
  - todo
  - clarify
YAML
    python3 - "$home" <<'PY'
import sys, pathlib
home = pathlib.Path(sys.argv[1])
(home / "MEMORY.md").write_text("\n".join(
    "- %d. Something Alfie learned about this person." % i for i in range(200)))
(home / "USER.md").write_text("Name: Test Person\nTimezone: Asia/Jerusalem\n")
PY
  fi
  cat > "$home/.env" <<ENV
OPENAI_BASE_URL=http://127.0.0.1:$PORT/v1
OPENAI_API_KEY=stub-not-a-real-key
ENV
}

# The product's environment, with $HOME_DIR bound to this turn's home. Read as
# data: no eval, so a value cannot become a command.
product_env() {
  local home="$1"
  while IFS= read -r line; do
    [[ -z "$line" || "$line" == \#* ]] && continue
    local key="${line%%=*}" value="${line#*=}"
    if [[ "${MOE_COLDSTART_NO_PROXY:-1}" == "0" && "$key" == *[Pp][Rr][Oo][Xx][Yy]* ]]; then
      continue
    fi
    printf '%s=%s\n' "$key" "${value//\$HOME_DIR/$home}"
  done < "$ENV_FILE"
}

run_one() {
  local n="$1"
  local home="$ROOT/tenant-$PROFILE-$n"
  rm -rf "$home"
  mkdir -p "$home" "$home/tmp" "$home/claude"
  write_config "$home"
  printf '%s' "Did I say I would call the dentist?" > "$ROOT/prompt.txt"

  local -a envargs=()
  while IFS= read -r pair; do envargs+=("$pair"); done < <(product_env "$home")
  # What a deployment supplies, which is not a tenant's business and so is not
  # in TenantHome.environment(): where Hermes is, and how to reach the model.
  envargs+=("HERMES_CHECKOUT=$HERMES")
  envargs+=("OPENAI_BASE_URL=http://127.0.0.1:$PORT/v1")
  envargs+=("OPENAI_API_KEY=stub-not-a-real-key")
  envargs+=("PYTHONDONTWRITEBYTECODE=1")

  local t0
  t0=$($PY -c "import time;print('%.6f'%time.time())")
  echo "SPAWN $t0 run$n" >> "$STUB_STAMPS"
  env -i "${envargs[@]}" \
    "$PY" "$SELF/../moe-hermes-turn.py" \
    < "$ROOT/prompt.txt" > "$ROOT/out-$PROFILE-$n.txt" 2> "$ROOT/err-$PROFILE-$n.txt"
  local rc=$?
  local t2
  t2=$($PY -c "import time;print('%.6f'%time.time())")
  echo "DONE $t2 run$n rc=$rc" >> "$STUB_STAMPS"
  rm -rf "$home"
}

for n in $(seq 1 "$RUNS"); do run_one "$n"; done

echo "=== profile: $PROFILE ==="
if [[ "${MOE_COLDSTART_NO_PROXY:-1}" == "0" ]]; then
    echo "note: proxy variables removed — measuring what the product cost before the fix"
fi
python3 "$SELF/report.py" "$STUB_STAMPS"
echo "=== the reply, run 1 ==="
head -3 "$ROOT/out-$PROFILE-1.txt"
